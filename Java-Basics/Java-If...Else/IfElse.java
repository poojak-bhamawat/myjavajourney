public class IfElse{
    public static void main(String[] args) {
        // Using boolean variable
        boolean isRaining = true;
        if(isRaining){
            System.out.println("Take an umbrella"); 
        }

        // If without curly braces
        if (20 > 18)
            System.out.println("20 is greater than 18"); 
    }
}